'use strict';
/* Builds the static pages for a split deployment: pages on a static host (Netlify), game server elsewhere (Render).
 *   node tools/build-static.js --server=https://your-game-server.onrender.com [--out=dist-static]
 * The game server must have PUBLIC_URL set to the static site's address, or it will reject the pages' WebSockets. */
const fs = require('fs');
const path = require('path');

const args = Object.fromEntries(process.argv.slice(2).map((a) => a.replace(/^--/, '').split(/=(.*)/s).slice(0, 2)));
if (!args.server || !/^https:\/\/[^/]+$/.test(args.server.replace(/\/+$/, ''))) {
  console.error('Usage: node tools/build-static.js --server=https://game-server.example.com [--out=dist-static]');
  process.exit(1);
}
const server = new URL(args.server);
const wss = `wss://${server.host}`;
const ROOT = path.join(__dirname, '..');
const out = path.resolve(ROOT, args.out || 'dist-static');

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(ROOT, 'public'), out, { recursive: true });
fs.cpSync(path.join(ROOT, 'shared'), path.join(out, 'shared'), { recursive: true });

fs.writeFileSync(path.join(out, 'config.js'), `/* Generated by tools/build-static.js */\nwindow.TAMBOLA_SERVER = ${JSON.stringify(wss)};\n`);

// QR codes are drawn by the game server (it knows which rooms exist); proxy them through so the page stays same-origin.
fs.writeFileSync(path.join(out, '_redirects'), [
  `/qr.svg  ${server.origin}/qr.svg  200`,
  '/host    /host.html  200',
  '',
].join('\n'));

// Same security headers the Node server sends, with the game server allowed for WebSockets.
const csp = `default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self' ${wss}; frame-ancestors 'none'; base-uri 'none'; form-action 'none'`;
fs.writeFileSync(path.join(out, '_headers'), [
  '/*',
  '  X-Content-Type-Options: nosniff',
  '  X-Frame-Options: DENY',
  '  Referrer-Policy: no-referrer',
  `  Content-Security-Policy: ${csp}`,
  '/config.js',
  '  Cache-Control: no-cache',
  '',
].join('\n'));

console.log(`Static site written to ${out}\n  game server: ${wss}`);
